# Feature: harmonized-fire-calendar, Property 35: Export file names are safe
"""Property test for `hotspots.export.filenames` (Validates: Requirements 18.3).

Inputs are synthetic. `tests/data/filename_vectors.json` holds shared vectors (inputs and the
Python outputs) that `web/src/lib/filenames.property.test.ts` checks the TypeScript port against.
To rewrite it after changing a vector, run from the project root:

    uv run python -c "from tests.property.test_export_filenames import write_vectors as w; w()"
"""

from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path
from typing import Any

from hypothesis import given
from hypothesis import strategies as st

from hotspots.export.filenames import MAX_STEM_CHARS, export_filename, sanitize_filename

VECTORS_PATH = Path(__file__).resolve().parents[1] / "data" / "filename_vectors.json"

SAFE_STEM = re.compile(r"[A-Za-z0-9_-]+")

# Free text with hostile characters mixed in: separators, dots, spaces, accents, CJK, controls.
_fragments = st.one_of(
    st.text(max_size=20),
    st.sampled_from(list('/\\.. :*?"<>|%\n\t') + ["é", "ñ", "ü", "日本", "..", "\x00"]),
)
_text = st.lists(_fragments, max_size=40).map("".join)
_dates = st.dates(min_value=date(2000, 1, 1), max_value=date(2100, 12, 31))
_kind = st.one_of(
    st.sampled_from(["hotspots", "calendar", "analytics"]), _text.map(lambda t: t[:60])
)
_extension = st.from_regex(r"[a-z0-9]{1,10}", fullmatch=True)


@given(kind=_kind, area=_text, start=_dates, end=_dates, extension=_extension)
def test_export_filename_is_safe_bounded_and_deterministic(
    kind: str, area: str, start: date, end: date, extension: str
) -> None:
    name = export_filename(kind, area, start, end, extension)
    again = export_filename(kind, area, start, end, extension)
    assert name == again
    stem, dot, ext = name.rpartition(".")
    assert dot == "." and ext == extension
    assert SAFE_STEM.fullmatch(stem)
    assert len(stem) <= MAX_STEM_CHARS


@given(text=_text, max_chars=st.integers(min_value=1, max_value=150))
def test_sanitize_filename_is_safe_and_bounded(text: str, max_chars: int) -> None:
    out = sanitize_filename(text, max_chars)
    assert SAFE_STEM.fullmatch(out)
    assert len(out) <= max_chars
    assert out == sanitize_filename(text, max_chars)


def test_long_area_keeps_dates() -> None:
    name = export_filename("hotspots", "x" * 500, date(2020, 1, 1), date(2020, 12, 31), "csv")
    assert len(name) - len(".csv") <= MAX_STEM_CHARS
    assert name.endswith("_2020-01-01_2020-12-31.csv")


_SANITIZE_INPUTS = [
    "",
    "   ",
    "///",
    "../../etc/passwd",
    "Sierra Nevada",
    "Café Ñandú",
    "日本語",
    "a  b\tc\nd",
    "--lead_trail__",
    "name.with.dots",
    "x" * 250,
    "ab-" * 60,
    "ﬁne ① ２",
]
_EXPORT_INPUTS = [
    ("hotspots", "Sierra Nevada", "2020-01-01", "2020-12-31", "csv"),
    ("calendar", "../../x", "2001-02-03", "2002-03-04", "png"),
    ("hotspots", "日本語", "2000-11-01", "2026-11-15", "svg"),
    ("analytics", "y" * 400, "2000-11-01", "2026-11-15", "csv"),
    ("a" * 80, "Café", "2010-05-05", "2010-05-06", "csv"),
    ("", "", "2015-06-01", "2015-06-30", "png"),
]


def build_vectors() -> dict[str, Any]:
    return {
        "note": "Generated by tests/property/test_export_filenames.py (Python is the reference).",
        "sanitize": [
            {"text": t, "max_chars": m, "expected": sanitize_filename(t, m)}
            for t in _SANITIZE_INPUTS
            for m in (MAX_STEM_CHARS, 10)
        ],
        "export": [
            {
                "kind": k,
                "area": a,
                "start": s,
                "end": e,
                "extension": x,
                "expected": export_filename(k, a, date.fromisoformat(s), date.fromisoformat(e), x),
            }
            for k, a, s, e, x in _EXPORT_INPUTS
        ],
    }


def write_vectors() -> None:
    VECTORS_PATH.parent.mkdir(parents=True, exist_ok=True)
    VECTORS_PATH.write_text(
        json.dumps(build_vectors(), indent=1, ensure_ascii=False) + "\n", encoding="utf-8"
    )


def test_vectors_file_is_current() -> None:
    stored = json.loads(VECTORS_PATH.read_text(encoding="utf-8"))
    assert stored == json.loads(json.dumps(build_vectors()))
